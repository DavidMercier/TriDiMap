function h = TriDiMap_addMLControls(h)
if isfield(h, 'pm_mlFeatures_GUI') && isgraphics(h.pm_mlFeatures_GUI) && ...
        ancestor(h.pm_mlFeatures_GUI, 'figure') == h.MainWindow
    return
end
set(h.pm_sectPlot_GUI, 'String', ...
    {'No clusters', 'Plot sectors', 'Gaussian Mixture Model', 'ML-assisted clustering'});
fields = {'pm_mlFeatures_GUI', 'pm_mlMethod_GUI', 'pm_mlOrder_GUI', 'pm_mlView_GUI'};
choices = {{'Features: H,E', 'Features: H,E,KAMM', 'Features: H/E, H^3/E^2', 'Features: all (9)'}, ...
    {'K-means (base MATLAB)', 'GMM (Statistics Toolbox)'}, ...
    {'KAMM order: 1', 'KAMM order: 2'}, ...
    {'E-H clusters', 'Phase map', 'KAMM map', 'Joint phase PDFs (3D)'}};
for ii = 1:numel(fields)
    h.(fields{ii}) = uicontrol('Parent', h.bg2_property_GUI_3, ...
        'Units', 'normalized', 'Style', 'popupmenu', ...
        'Position', [0.02, 0.74-(ii-1)*0.18, 0.94, 0.12], ...
        'String', choices{ii}, 'Value', 1, 'Visible', 'off', ...
        'Callback', 'TriDiMap_runPlot');
end
set(h.pm_mlFeatures_GUI, 'Value', 2, ...
    'TooltipString', 'Features are z-score standardized. Missing/nonpositive pairs remain unassigned.');
h.pb_mlExport_GUI = uicontrol('Parent', h.bg2_property_GUI_3, ...
    'Units', 'normalized', 'Style', 'pushbutton', 'Position', [0.02, 0.02, 0.94, 0.14], ...
    'String', 'Export ML CSV', 'Visible', 'off', 'Enable', 'off', 'Callback', 'TriDiMap_exportML');
h.pm_mlMetric_GUI = uicontrol('Parent', h.bg_property_GUI_3, ...
    'Units', 'normalized', 'Style', 'popupmenu', 'Position', [0.02, 0.43, 0.80, 0.12], ...
    'String', {'KAMM', 'KAEM', 'KAPM', 'KAMM_RATIO', 'KAMM_NORMPROD'}, ...
    'TooltipString', 'Descriptor shown in the KAMM map view; this does not change clustering features.', ...
    'Value', 1, 'Visible', 'off', 'Callback', 'TriDiMap_runPlot');
end
